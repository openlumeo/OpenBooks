"""Rescore saved weights and calibration on a locally generated synthetic split cache."""
import argparse
import math
import pickle
from pathlib import Path

import torch

import train_roles as tr
from openbooks.statements.assets import ModelUnavailable
from openbooks.statements.roles import RoleModel
from role_candidates import sha256, split_sha256, write_json


def main() -> int:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--model-dir", type=Path, default=tr.ROOT / "models")
    cli.add_argument("--dataset", type=Path, default=tr.ROOT / "data" / "roles_dataset_1200_150.pkl",
                     help="Trusted local pickle generated by train_roles.py")
    cli.add_argument("--out", type=Path, required=True)
    cli.add_argument("--threads", type=int, default=4)
    args = cli.parse_args()
    if args.threads < 1:
        cli.error("--threads must be positive")
    torch.set_num_threads(args.threads)
    try:
        model = RoleModel.load(args.model_dir / "roles_head.pt", args.model_dir / "roles_calibration.json")
        if model is None:
            cli.error("Model weights or calibration are missing")
        splits = pickle.loads(args.dataset.read_bytes())
    except ModelUnavailable as e:
        cli.error(e.message)
    except (OSError, pickle.UnpicklingError) as e:
        cli.error(str(e))

    role_cal = model.role_cal
    metrics = {"calibration": {"role_temperature": role_cal.temperature, "alpha": role_cal.alpha,
                               "role_qhat": role_cal.qhat if math.isfinite(role_cal.qhat) else None}}
    for name in ("calib", "test", "shifted"):
        logits = tr.logits_of(model.net, splits[name], model.dev)
        metrics[name] = tr.report(*logits, model.role_cal, model.type_cal)
        if name != "calib":
            metrics[name]["split_sha256"] = split_sha256(splits[name])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_json(args.out, {"int8_shipped": metrics, "model": model.identity, "dataset_sha256": sha256(args.dataset),
                          "note": "Synthetic statements only. The saved calibration was applied without refitting."})
    print(f"Rescored model: {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
